def main() -> None:
    with SOURCE.open("r", encoding="utf-8-sig", newline="") as source_file:
        source_rows = list(csv.reader(source_file))
    if not source_rows or source_rows[0] != ["keys", "en"]:
        raise ValueError("strings.csv must have the header keys,en")

    source_keys = [row[0] for row in source_rows[1:]]
    for locale, values in TRANSLATIONS.items():
        if len(values) != len(source_keys):
            raise ValueError(f"{locale}: {len(values)} translations for {len(source_keys)} keys")
        output = ROOT / "game" / "locale" / f"strings_{locale}.csv"
        with output.open("w", encoding="utf-8", newline="") as output_file:
            writer = csv.writer(output_file, lineterminator="\n")
            writer.writerow(["keys", locale])
            for key, translation in zip(source_keys, values):
                if not translation:
                    raise ValueError(f"{locale}: empty translation for {key!r}")
                if translation.count("%") != key.count("%"):
                    raise ValueError(f"{locale}: percent count mismatch for {key!r}")
                writer.writerow([key, translation])
        print(f"{locale}: wrote {len(values)} rows to {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
